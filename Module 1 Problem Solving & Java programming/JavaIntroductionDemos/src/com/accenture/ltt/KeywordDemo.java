package com.accenture.ltt;

/**
 * Demonstrates basic Java keywords used in a class structure.
 */
public class KeywordDemo {
    public static void main(String[] args) {
        // 'public' means this method is accessible to all
        // 'static' allows the method to run without creating an instance
        // 'void' means the method doesn't return anything
        System.out.println("Demonstrating class, public, static, void, etc.");
    }
}