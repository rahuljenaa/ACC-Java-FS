package com.accenture.ltt;

/**
 * Demonstrates different primitive data types in Java.
 */
public class DatatypeDemo {
    public static void main(String[] args) {
        int number = 25;             // Integer type
        double price = 19.99;        // Double (floating point number)
        char letter = 'A';           // Character type
        boolean flag = true;         // Boolean type

        // Printing each variable
        System.out.println("Int: " + number);
        System.out.println("Double: " + price);
        System.out.println("Char: " + letter);
        System.out.println("Boolean: " + flag);
    }
}